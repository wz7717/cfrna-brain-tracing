def verify_raw_data() -> dict[str, str]:
    """Verify SHA256 of all raw data sources against SHA256SUMS.txt."""
    print("=" * 70)
    print("STEP 0: Verifying raw data integrity (SHA256) ...")
    print("=" * 70)

    # Parse SHA256SUMS
    expected: dict[str, str] = {}
    if SHA256SUMS.exists():
        with open(SHA256SUMS) as f:
            for line in f:
                line = line.strip()
                if not line or line.startswith("#"):
                    continue
                parts = line.split()
                if len(parts) >= 2:
                    expected[parts[-1]] = parts[0]

    results: dict[str, str] = {}
    all_pass = True

    for label, rel_path in RAW_DATA_SOURCES.items():
        full_path = ROOT / rel_path
        if not full_path.exists():
            status = "MISSING"
            all_pass = False
        else:
            actual = sha256_file(full_path)
            if rel_path in expected:
                if actual == expected[rel_path]:
                    status = "OK"
                else:
                    status = f"HASH_MISMATCH (expected {expected[rel_path][:12]}..., got {actual[:12]}...)"
                    all_pass = False
            else:
                status = f"NOT_IN_MANIFEST (hash={actual[:12]}...)"
        results[label] = status
        icon = " PASS " if status == "OK" else " FAIL " if status != "NOT_IN_MANIFEST" else " WARN "
        print(f"  [{icon}] {label}: {rel_path} — {status}")

    if not all_pass:
        print("\n  WARNING: Some raw data files failed verification.")
        print("  Results may not be reproducible until issues are resolved.")
    else:
        print("\n  All raw data files verified successfully.")

    return results


def capture_environment() -> dict:
    """Capture Python environment for reproducibility."""
    result = subprocess.run(
        [sys.executable, "-m", "pip", "freeze"],
        capture_output=True,
        text=True,
        timeout=30,
    )
    packages = {}
    for line in result.stdout.strip().split("\n"):
        if "==" in line:
            pkg, ver = line.split("==", 1)
            packages[pkg] = ver

    return {
        "python_version": sys.version,
        "platform": platform.platform(),
        "hostname": platform.node(),
        "packages": packages,
    }


def execute_pipeline(
    steps: list[BuildStep],
    phase: str,
    skip_build: bool = False,
) -> list[AuditRecord]:
    """Execute a list of build/validation steps."""
    records: list[AuditRecord] = []
    total = len(steps)
    passed = 0
    failed = 0
    skipped = 0

    for i, step in enumerate(steps, 1):
        print(f"\n{'─' * 70}")
        print(f"STEP {phase}.{i}/{total}: {step.name}")
        print(f"  Description: {step.description}")

        if skip_build and phase == "BUILD":
            print("  [SKIP] --skip-build flag set, using pre-built assets")
            records.append(
                AuditRecord(step=step.name, status="SKIP", duration_sec=0.0, notes="--skip-build")
            )
            skipped += 1
            continue

        # Verify dependencies
        missing_deps = []
        for dep in step.depends_on:
            if not (ROOT / dep).exists():
                missing_deps.append(dep)

        if missing_deps:
            print(f"  [SKIP] Missing dependencies: {', '.join(missing_deps)}")
            records.append(
                AuditRecord(
                    step=step.name,
                    status="SKIP",
                    duration_sec=0.0,
                    notes=f"Missing deps: {missing_deps}",
                )
            )
            skipped += 1
            continue

        # Verify input checksums
        input_checksums = {}
        for dep in step.depends_on:
            dep_path = ROOT / dep
            if dep_path.is_file():
                input_checksums[dep] = sha256_file(dep_path)
            elif dep_path.is_dir():
                input_checksums[dep] = "DIRECTORY"

        # Set seed environment
        extra_env = {}
        if step.seed and step.seed in SEED_REGISTRY:
            extra_env["BRAINTRACE_SEED"] = str(SEED_REGISTRY[step.seed])

        # Run step
        extra_args = list(step.extra_args)
        if step.seed and step.seed in SEED_REGISTRY and "--seed" in " ".join(sys.argv):
            extra_args.extend(["--seed", str(SEED_REGISTRY[step.seed])])

        rc, output, elapsed = run_step(step.script, extra_args, env=extra_env)

        # Verify outputs
        output_checksums = {}
        all_outputs_exist = True
        for out_rel in step.produces:
            out_path = ROOT / out_rel
            if out_path.is_file():
                output_checksums[out_rel] = sha256_file(out_path)
            elif out_path.is_dir() and any(out_path.iterdir()):
                output_checksums[out_rel] = "DIRECTORY_EXISTS"
            else:
                all_outputs_exist = False
                output_checksums[out_rel] = "MISSING"

        if rc == 0 and all_outputs_exist:
            status = "PASS"
            passed += 1
            icon = " PASS "
        elif rc != 0:
            status = "FAIL"
            failed += 1
            icon = " FAIL "
        else:
            status = "WARN"
            failed += 1
            icon = " WARN "

        record = AuditRecord(
            step=step.name,
            status=status,
            duration_sec=elapsed,
            output_checksums=output_checksums,
            input_checksums=input_checksums,
            notes=f"Exit code: {rc}" if rc != 0 else "",
        )
        records.append(record)

        print(f"  [{icon}] {status} ({elapsed:.1f}s)")

        # Show abbreviated output on failure
        if rc != 0:
            print(f"  --- STDERR tail ---")
            err_lines = output.split("\n")
            for line in err_lines[-10:]:
                if line.strip():
                    print(f"    {line[:120]}")

    print(f"\n  Phase {phase} summary: {passed} passed, {failed} failed, {skipped} skipped")
    return records


def generate_report(
    raw_data_results: dict,
    build_records: list[AuditRecord],
    validation_records: list[AuditRecord],
    env_info: dict,
) -> AuditReport:
    """Generate the complete audit report."""
    report = AuditReport(
        generated_at=datetime.now(timezone.utc).isoformat(),
        hostname=env_info["hostname"],
        platform=env_info["platform"],
        python_version=env_info["python_version"],
        pip_freeze=env_info["packages"],
        seed_registry=SEED_REGISTRY,
        raw_data_verification=raw_data_results,
        build_steps=build_records,
        validation_steps=validation_records,
    )

    # Collect final output checksums
    for step_list in [build_records, validation_records]:
        for record in step_list:
            for path, checksum in record.output_checksums.items():
                if checksum not in ("MISSING", "DIRECTORY_EXISTS", "DIRECTORY"):
                    report.final_output_checksums[path] = checksum

    # Write JSON report
    report_path = REPRO_DIR / "reproducibility_audit.json"
    with open(report_path, "w", encoding="utf-8") as f:
        json.dump(report, f, indent=2, ensure_ascii=False, default=str)
    print(f"\n  Audit report written to: {report_path}")

    # Write human-readable summary
    summary_path = REPRO_DIR / "reproducibility_summary.txt"
    with open(summary_path, "w", encoding="utf-8") as f:
        f.write("=" * 70 + "\n")
        f.write("BrainTrace — Reproducibility Audit Summary\n")
        f.write(f"Generated: {report.generated_at}\n")
        f.write(f"Platform: {report.platform}\n")
        f.write(f"Python: {report.python_version}\n")
        f.write("=" * 70 + "\n\n")

        f.write("RAW DATA VERIFICATION\n")
        f.write("-" * 40 + "\n")
        for label, status in raw_data_results.items():
            f.write(f"  {label}: {status}\n")

        for phase_name, records in [("BUILD", build_records), ("VALIDATION", validation_records)]:
            f.write(f"\n{phase_name} STEPS\n")
            f.write("-" * 40 + "\n")
            for r in records:
                f.write(f"  {r.step}: {r.status} ({r.duration_sec:.1f}s)\n")
                if r.notes:
                    f.write(f"    Notes: {r.notes}\n")

        f.write(f"\nSEED REGISTRY\n")
        f.write("-" * 40 + "\n")
        for name, seed in SEED_REGISTRY.items():
            f.write(f"  {name}: {seed}\n")

        f.write(f"\nFINAL OUTPUT CHECKSUMS ({len(report.final_output_checksums)} files)\n")
        f.write("-" * 40 + "\n")
        for path, checksum in sorted(report.final_output_checksums.items()):
            f.write(f"  {checksum}  {path}\n")

    print(f"  Summary written to: {summary_path}")
    return report


def main() -> int:
    parser = argparse.ArgumentParser(
        description="BrainTrace Master Reproducibility Pipeline",
        formatter_class=argparse.RawDescriptionHelpFormatter,
        epilog="""
Examples:
  python reproduce_all.py                          # Run everything
  python reproduce_all.py --verify-only            # Only verify raw data
  python reproduce_all.py --skip-build             # Skip asset building (use pre-built)
  python reproduce_all.py --step network_model     # Run a single step
        """,
    )
    parser.add_argument("--verify-only", action="store_true", help="Only verify raw data SHA256")
    parser.add_argument("--skip-build", action="store_true", help="Skip model/DB build steps")
    parser.add_argument("--step", type=str, help="Run a single named step")
    parser.add_argument("--output-dir", type=Path, default=REPRO_DIR)
    args = parser.parse_args()

    # Capture environment
    print("=" * 70)
    print("BrainTrace — Reproducibility Pipeline")
    print(f"  Python: {sys.version}")
    print(f"  Platform: {platform.platform()}")
    print(f"  Root: {ROOT}")
    print(f"  Audit dir: {args.output_dir}")
    print("=" * 70)

    env_info = capture_environment()
    print(f"\n  Found {len(env_info['packages'])} installed Python packages.")

    # Step 0: Verify raw data
    raw_results = verify_raw_data()

    if args.verify_only:
        print("\n  --verify-only mode: skipping build and validation steps.")
        return 0

    # ── Pre-build: Extract nested archives ─────────────────────────────────
    print("\n" + "=" * 70)
    print("PRE-BUILD: Extracting nested archives ...")
    print("=" * 70)

    brats_ok = True
    if not args.skip_build:
        print("\n  [BraTS-TCGA-LGG NIfTI extraction]")
        brats_ok = extract_brats_nested_zip()
        if not brats_ok:
            print("  WARNING: BraTS extraction failed. TCGA/BraTS validation may be skipped.")
    else:
        print("  [SKIP] --skip-build flag set, assuming data is already extracted")

    # ── Build assets ──────────────────────────────────────────────────────
    if args.step:
        # Run a single step
        all_steps = {s.name: s for s in BUILD_STEPS + VALIDATION_STEPS}
        if args.step not in all_steps:
            print(f"Unknown step: {args.step}")
            print(f"Available: {sorted(all_steps)}")
            return 1
        target = all_steps[args.step]
        phase_steps = [s for s in BUILD_STEPS if s.name == args.step] or [
            s for s in VALIDATION_STEPS if s.name == args.step
        ]
        build_records = execute_pipeline(
            phase_steps if phase_steps[0] in BUILD_STEPS else [], "BUILD", args.skip_build
        )
        validation_records = execute_pipeline(
            phase_steps if phase_steps[0] in VALIDATION_STEPS else [], "VALIDATION"
        )
    else:
        # Full pipeline
        build_records = execute_pipeline(BUILD_STEPS, "BUILD", args.skip_build)
        validation_records = execute_pipeline(VALIDATION_STEPS, "VALIDATION")

    # Generate report
    report = generate_report(raw_results, build_records, validation_records, env_info)

    # Final summary
    build_pass = sum(1 for r in build_records if r.status == "PASS")
    build_total = len(build_records)
    val_pass = sum(1 for r in validation_records if r.status == "PASS")
    val_total = len(validation_records)

    print(f"\n{'=' * 70}")
    print(f"PIPELINE COMPLETE")
    print(f"  Build:     {build_pass}/{build_total} passed")
    print(f"  Validation: {val_pass}/{val_total} passed")
    print(f"  Audit report: {args.output_dir / 'reproducibility_audit.json'}")
    print(f"  Human summary: {args.output_dir / 'reproducibility_summary.txt'}")
    print(f"{'=' * 70}")

    return 0 if (build_pass == build_total and val_pass == val_total) else 1


if __name__ == "__main__":
    sys.exit(main())
