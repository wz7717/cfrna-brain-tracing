def extract_brats_nested_zip() -> bool:
    """Extract the nested BraTS-TCGA-LGG NIfTI zip if not already done.

    The BraTS data arrives as a nested package:
      data/brats_tcga_lgg_training_65/
        PKG - BraTS-TCGA-LGG/BraTS-TCGA-LGG/Pre-operative_TCGA_LGG_NIfTI_and_Segmentations.zip

    This step extracts it into:
      data/brats_tcga_lgg_training_65/extracted/
    """
    brats_dir = ROOT / "data" / "brats_tcga_lgg_training_65"
    zip_path = brats_dir / "PKG - BraTS-TCGA-LGG" / "BraTS-TCGA-LGG" / "Pre-operative_TCGA_LGG_NIfTI_and_Segmentations.zip"
    extract_dir = brats_dir / "extracted"

    if not zip_path.exists():
        print(f"  [SKIP] BraTS zip not found at: {zip_path}")
        print(f"  This is expected if running with --skip-build or if data is already extracted.")
        return True  # Not an error — data may already be extracted

    # Check if already extracted (at least 50 patient directories)
    if extract_dir.exists():
        n_dirs = sum(1 for p in extract_dir.iterdir() if p.is_dir())
        if n_dirs >= 50:
            print(f"  [OK] BraTS data already extracted ({n_dirs} patient directories)")
            return True

    # Extract
    print(f"  Extracting {zip_path.name} ({zip_path.stat().st_size / 1e6:.0f} MB)...")
    extract_dir.mkdir(parents=True, exist_ok=True)
    try:
        with zipfile.ZipFile(zip_path, "r") as zf:
            zf.extractall(extract_dir)
        n_dirs = sum(1 for p in extract_dir.iterdir() if p.is_dir())
        print(f"  [OK] Extracted {n_dirs} patient directories")
        return True
    except Exception as e:
        print(f"  [FAIL] Extraction error: {e}")
        return False


