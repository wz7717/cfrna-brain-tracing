# ── Utility functions ────────────────────────────────────────────────────────


def sha256_file(path: Path) -> str:
    """Compute SHA256 hex digest of a file."""
    h = hashlib.sha256()
    with open(path, "rb") as f:
        while True:
            chunk = f.read(65536)
            if not chunk:
                break
            h.update(chunk)
    return h.hexdigest()


def sha256_content(text: str) -> str:
    """Compute SHA256 of a string."""
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


def run_step(
    script: Path,
    args: list[str],
    cwd: Path | None = None,
    timeout: int = 3600,
    env: dict | None = None,
) -> tuple[int, str, float]:
    """Run a Python script, capturing stdout/stderr and timing."""
    start = time.perf_counter()
    full_args = [sys.executable, str(script)] + args
    result = subprocess.run(
        full_args,
        cwd=str(cwd or ROOT),
        capture_output=True,
        text=True,
        timeout=timeout,
        env={**os.environ, **(env or {})},
    )
    elapsed = time.perf_counter() - start
    return result.returncode, result.stdout + "\n" + result.stderr, elapsed


