"""
BrainTrace — Master Reproducibility Pipeline
=============================================
End-to-end reproduction of all reported results.

Pipeline phases:
  PRE-BUILD  — Extract nested archives (BraTS NIfTI zip)
  BUILD      — Generate all derived assets from raw data
               1. atlas_database  — braintrace_source_tracing.db (~730 MB)
               2. network_model   — bo2023_saleem_network_top200_model.npz
               3. reference_projector — projected-VSD projector + reference matrices
               4. reference_db    — Streamlit web app SQLite DB
  VALIDATION — Run all validation experiments (LOMO, AHBA, TCGA/BraTS, etc.)
  CSV-GEN    — Regenerate all 10 manuscript CSV files from documented raw counts

Traceability system:
  - DATA_PROVENANCE.md     — Raw data source manifest (accessions, DOIs, SHA256)
  - generate_all_csvs.py   — Dynamic CSV regeneration from raw counts + formulas
  - TRACEABILITY_MATRIX.md — Manuscript number → CSV → formula → raw data mapping

Usage:
    python reproduce_all.py [--verify-only] [--skip-build] [--output-dir DIR]
    python reproduce_all.py --step network_model   # Run a single step

Design principles:
    1. Every input is SHA256-verified before use.
    2. Every random component is pinned to a documented seed.
    3. Every output is checksummed and logged.
    4. The pipeline is idempotent — re-running produces identical results.

Key architectural note:
  The main atlas database (braintrace_source_tracing.db) is a BUILD ARTIFACT
  generated by Step 1 (atlas_database: build_bo2023_atlas_from_wang_matrix.py).
  It is regenerated from the raw data files — it is NOT a pre-existing dependency.
  The pre-built DB is provided as a convenience to skip this expensive step
  via --skip-build.

  The Streamlit reference DB (braintrace_reference_v1.sqlite) is a
  separate, lightweight database built by Step 4 (reference_db).
"""

